namespace SpreadsheetEditor.Services;


public sealed class HelpProvider
{
    private const string Text = """
        ЕЛЕКТРОННІ ТАБЛИЦІ (лабораторна робота №1*, варіант 8)

        Клітинка містить арифметичний вираз із цілих чисел довільної довжини, круглих дужок і посилань на інші клітинки (A1, B12, AA3).

        Операції:
        • бінарні: + − * / (результат ділення округлюється до цілого, рівно половина — до більшого: 7/2 = 4, −7/2 = −3);
        • унарні: + і −;
        • ^ — піднесення до степеня (2^3^2 = 2^9; −2^2 = −4); 
        від'ємний степінь дає результат, округлений до цілого, а рівно половина — до більшого (2^-1 = 1, (-2)^-1 = 0, 2^-2 = 0);
        • функції inc(x) і dec(x) — збільшити/зменшити на 1.
        Помилкою вважається лише ділення на нуль (зокрема 0 у від'ємному степені).
        Пропуски у виразах ігноруються. Порожня клітинка дорівнює 0.

        Робота:
        • клацніть клітинку, введіть вираз і перейдіть до іншої — значення буде обчислено;
        • під час введення клітинки, на які ви посилаєтесь, обводяться й підсвічуються блакитним;
        • «Режим» перемикає відображення ВИРАЗ / ЗНАЧЕННЯ;
