        • помилка показується як #ПОМИЛКА, а її місце й опис — у рядку стану внизу;
        • «Зберегти», «Зберегти як…», «Нещодавні» працюють з локальними файлами;
        • «Google Drive» зберігає й відкриває таблиці у вашому Google Drive (потрібен вхід в акаунт Google).
        """;

    public string GetHelpText() => Text;
}